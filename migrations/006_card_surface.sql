-- NekoTab 迁移 006：卡片的面（底色）
--
-- 内容类组件（记事本、天气、表盘）的文字与细线原来直接压在壁纸上，能不能看清全看壁纸
-- 是什么样。书签卡不受这个影响——它的内容是"彩色图标块 + 一行短标题"，图标块自带底色
-- 和投影，所以参照各家新标签页的做法，书签保持透明、内容卡各有一层底。
--
-- 这一列**加在卡片上、与 kind 无关**，而不是塞进组件的 config：
--   1. 它是"卡片"的属性，不是"某种组件"的参数。放进 config 就得给四种组件的参数
--      结构各加一份同样的字段，还要在渲染处按 kind 分叉去取（或按字段名硬取）。
--   2. 将来书签卡想加面，这一列直接用，不必再动表。
--
-- 取值（白名单见 src/models.rs 的 CARD_SURFACES）：
--   ''      没设过 —— 用该种类的默认（组件卡有面、书签卡没有）
--   'none'  明确不要面
--   'panel' 半透明面板（带背景模糊）
--   'solid' 实底
--
-- 默认空串，于是这次迁移对既有数据零行为变化。"组件卡默认有面"落在渲染时的默认上、
-- 不进库，这样以后改默认值会一并作用到已有卡片。
ALTER TABLE bookmarks ADD COLUMN surface TEXT NOT NULL DEFAULT '';
